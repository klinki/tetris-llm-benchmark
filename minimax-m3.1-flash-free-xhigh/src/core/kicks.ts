/**
 * Kick offsets for a rotation, in board coordinates. The piece tries the
 * offsets in order and uses the first one that does not collide.
 */
export function kicksFor(type: PieceType, from: Rotation, to: Rotation): readonly Cell[] {
  if (type === 'O') {
    return [{ x: 0, y: 0 }];
  }
  const table = type === 'I' ? I_KICKS : JLSTZ_KICKS;
  const offsets = table[`${from}${to}`] ?? [{ x: 0, y: 0 }];
  // The tables use an upwards y axis, the board uses a downwards one.
  return offsets.map((offset) => ({ x: offset.x, y: -offset.y }));
}
