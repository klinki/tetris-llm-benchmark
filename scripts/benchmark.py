class BenchmarkError(RuntimeError):
    pass


@dataclasses.dataclass
class Usage:
    input: int = 0
    cache_read: int = 0
    cache_write: int = 0
    output: int = 0
    total: int = 0
    cost: float = 0.0

    def validate(self, label: str) -> None:
        components = self.input + self.cache_read + self.cache_write + self.output
        if components != self.total:
            raise BenchmarkError(
                f"{label} token mismatch: {components:,} components != {self.total:,} total"
            )
        if min(self.input, self.cache_read, self.cache_write, self.output, self.total) < 0:
            raise BenchmarkError(f"{label} contains a negative token count")

    def __add__(self, other: "Usage") -> "Usage":
        return Usage(
            self.input + other.input,
            self.cache_read + other.cache_read,
            self.cache_write + other.cache_write,
            self.output + other.output,
            self.total + other.total,
            self.cost + other.cost,
        )

    def __sub__(self, other: "Usage") -> "Usage":
        return Usage(
            self.input - other.input,
            self.cache_read - other.cache_read,
            self.cache_write - other.cache_write,
            self.output - other.output,
            self.total - other.total,
            self.cost - other.cost,
        )


@dataclasses.dataclass
class Phase:
    number: int
    start_ms: float
    end_ms: float
    usage: Usage
    responses: int
    assistant_messages: int
    tool_calls: int
    tool_results: int
    model_errors: int
    tool_errors: int
    tool_types: dict[str, int]

    @property
    def elapsed_ms(self) -> float:
        return self.end_ms - self.start_ms


@dataclasses.dataclass
class RunResult:
    run: dict[str, Any]
    session_file: str
    phases: list[Phase]
    included_phases: list[Phase]
    tested: Usage
    overhead: Usage | None
    combined: Usage | None
    overhead_label: str
    overhead_count: int
    raw_tested_events: list[dict[str, Any]]
    raw_overhead_events: list[dict[str, Any]]
    average_duration_ms: float
    reasoning_output: int = 0

    @property
    def start_ms(self) -> float:
        return self.included_phases[0].start_ms

    @property
    def end_ms(self) -> float:
        return self.included_phases[-1].end_ms

    @property
    def raw_elapsed_ms(self) -> float:
        return self.end_ms - self.start_ms

    @property
    def active_elapsed_ms(self) -> float:
        if self.run["cutoff"].get("exclude_inter_message_wait", True):
            return sum(phase.elapsed_ms for phase in self.included_phases)
        return self.raw_elapsed_ms

    @property
    def excluded_wait_ms(self) -> float:
        return self.raw_elapsed_ms - sum(phase.elapsed_ms for phase in self.included_phases)


