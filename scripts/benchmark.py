def extract_report_values(path: Path, content: str | None = None) -> dict[str, Any]:
    text = content if content is not None else path.read_text()
    elapsed_match = re.search(r"^- Comparable implementation elapsed: \*\*(.+)\*\*$", text, re.M)
    if not elapsed_match:
        elapsed_match = re.search(r"^- Elapsed: (.+)$", text, re.M)
    if not elapsed_match:
        raise BenchmarkError(f"Cannot find elapsed time in {path}")
    values: dict[str, Any] = {"elapsed": elapsed_match.group(1)}
    for heading, key in [
        ("Tested-agent usage", "tested"),
        ("Harness overhead", "overhead"),
        ("Combined recorded usage", "combined"),
    ]:
        section_match = re.search(rf"## {re.escape(heading)}\n(.*?)(?=\n## |\Z)", text, re.S)
        if not section_match:
            raise BenchmarkError(f"Cannot find {heading} in {path}")
        rows = re.findall(r"^\|.*\|$", section_match.group(1), re.M)
        data_rows = [row for row in rows if "---" not in row and "Input" not in row and "Source" not in row]
        if not data_rows:
            raise BenchmarkError(f"Cannot parse {heading} table in {path}")
        cells = [cell.strip().replace("*", "").replace(",", "") for cell in data_rows[-1].strip("|").split("|")]
        if cells[-1] == "Not verified":
            if key == "tested" or any(cell != "Not verified" for cell in cells[-5:]):
                raise BenchmarkError(f"Invalid unknown-usage row in {path}")
            values[key] = None
        else:
            values[key] = int(cells[-1])
        if key == "tested":
            values["tested_usage"] = dict(zip(("input", "cache_read", "cache_write", "output"), map(int, cells[-5:-1])))
    values["elapsed_ms"] = parse_duration(values["elapsed"])
    recorded_cost = re.search(r"^\s+Tested agent: \$(\d+(?:\.\d+)?)$", text, re.M)
    values["recorded_cost"] = float(recorded_cost.group(1)) if recorded_cost else None
    for label, key in [("Tool calls", "tool_calls"), ("Model responses", "model_responses")]:
        match = re.search(rf"^- {label}: (\d+)$", text, re.M)
        values[key] = int(match.group(1)) if match else None
    return values


def render_readme_block(
    runs: list[dict[str, Any]], reports: dict[str, str], root: Path, ranking: dict[str, Any],
    pricing: dict[str, Any],
) -> str:
    lines = [README_START,
        "| # | Run | Model | Effort | Harness | Quality | Tokens | Est. cost | Time | Main finding |",
        "|---:|---|---|---|---|---:|---:|---:|---:|---|",
    ]
    by_id = {run["id"]: run for run in runs}
    rows: list[tuple[str, dict[str, Any], dict[str, Any] | None, Decimal | None]] = [
        (str(rank), by_id[entry["run_id"]], entry, score) for rank, entry, score in ranked_entries(ranking)
    ]
    scored_ids = {entry["run_id"] for entry in ranking["entries"]}
    rows.extend(("—", run, None, None) for run in runs if run["id"] not in scored_ids)
    notes: list[str] = []
    unknown_overhead = False
    for rank, run, entry, score in rows:
        path = root / run["project_dir"] / "STATISTICS.md"
        values = extract_report_values(path, reports.get(run["id"]))
        unknown_overhead |= values["overhead"] is None
        marker = "†" if run.get("comparison_note") else ""
        effort = f"`{run['reasoning_variant']}`" if run.get("reasoning_variant") else "—"
        quality = f"**{score}**" if score is not None else "Pending"
        finding = entry["summary"] if entry else "Not ranked yet"
        cost = format_cost(estimate_cost(values["tested_usage"], pricing["models"][run["model"]]))
        lines.append(
            f"| {rank} | [{run['label']}]({run['project_dir']}/STATISTICS.md){marker} | `{run['model']}` | "
            f"{effort} | {run['harness_label']} | {quality} | {values['tested']:,} | {cost} | {values['elapsed']} | "
            f"{finding} |"
        )
        if marker:
            notes.append(f"**† {run['label']}:** {run['comparison_note']}")
    notes.append(
        "**Columns:** Quality is the weighted [ranking](RANKING.md) score out of 10; token use and time "
        "do not affect it. Tokens are the tested agent's total (input + cache read + cache write + output). "
        "Effort is the recorded reasoning setting; `—` means it was not recorded. Effort labels are "
        "provider-specific, not equivalent reasoning budgets."
    )
    notes.append(
        "**Est. cost** prices the tested agent's tokens at the model's public API list price on the run date, "
        "from [`pricing.json`](pricing.json); `—` means the model has no public price. It is an estimate of the "
        "API cost, not what a subscription or free tier charged. Some prices come from third-party listings or "
        "are upper bounds; `pricing.json` records the source and caveats for each model."
    )
    if unknown_overhead:
        notes.append(
            "**Harness overhead:** each run's statistics report separate harness requests. "
            "For T3 runs they are not verified; unknown does not mean zero."
        )
    for note in notes:
        lines.extend(["", note])
    lines.append(README_END)
    return "\n".join(lines)


def render_ranking_table(runs: list[dict[str, Any]], ranking: dict[str, Any]) -> str:
    labels = {run["id"]: run["label"] for run in runs}
    weights = ranking["weights"]
    criteria = " | ".join(f"{label} ({weights[key]}%)" for key, label in CRITERIA)
    lines = [
        RANKING_START,
        f"| Rank | Implementation | {criteria} | Weighted score | Confirmed bugs |",
        "|---:|---|" + "---:|" * (len(CRITERIA) + 1) + "---:|",
    ]
    for rank, entry, score in ranked_entries(ranking):
        scores = " | ".join(f"{float(entry['scores'][key]):.1f}" for key, _ in CRITERIA)
        counts = bug_counts(entry)
        bugs = ", ".join(f"{counts[kind]} {kind}" for kind in BUG_KINDS if counts[kind]) or "0"
        lines.append(f"| {rank} | {labels[entry['run_id']]} | {scores} | **{score}** | {bugs} |")
    lines.append(RANKING_END)
    return "\n".join(lines)


def replace_marked_block(text: str, start: str, end: str, block: str, name: str) -> str:
    if text.count(start) != 1 or text.count(end) != 1:
        raise BenchmarkError(f"{name} generated-block markers are missing or malformed")
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    return pattern.sub(lambda _: block, text)


def render_documents(
    root: Path, runs: list[dict[str, Any]], reports: dict[str, str], ranking: dict[str, Any],
    pricing: dict[str, Any],
) -> dict[Path, str]:
    readme_path = root / "README.md"
    ranking_path = root / "RANKING.md"
    readme = replace_readme_block(
        readme_path.read_text(), render_readme_block(runs, reports, root, ranking, pricing),
    )
    ranking_md = replace_marked_block(
        ranking_path.read_text(), RANKING_START, RANKING_END, render_ranking_table(runs, ranking), "RANKING.md",
    )
    return {readme_path: readme, ranking_path: ranking_md}


def replace_readme_block(readme: str, block: str) -> str:
    if README_START in readme or README_END in readme:
        if readme.count(README_START) != 1 or readme.count(README_END) != 1:
            raise BenchmarkError("README benchmark-result markers are malformed")
        pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
        return pattern.sub(block, readme)
    table_start = readme.find("| Run | Harness | Elapsed |")
    next_heading = readme.find("\n## Token accounting", table_start)
    if table_start < 0 or next_heading < 0:
        raise BenchmarkError("Cannot locate the existing README results section")
    return readme[:table_start] + block + "\n" + readme[next_heading:]


def validate_project(root: Path, run: dict[str, Any]) -> None:
    project = root / run["project_dir"]
    for required in ("package.json", "package-lock.json"):
        if not (project / required).is_file():
            raise BenchmarkError(f"{run['id']} is missing {required}")
    with tempfile.TemporaryDirectory(prefix=f"benchmark-{run['id']}-") as temporary:
        destination = Path(temporary) / run["project_dir"]
        shutil.copytree(
            project,
            destination,
            ignore=shutil.ignore_patterns(".git", "node_modules", "dist"),
        )
        for command in (["npm", "ci", "--ignore-scripts"], ["npm", "test"]):
            process = subprocess.run(
                command,
                cwd=destination,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
            )
            if process.returncode:
                raise BenchmarkError(
                    f"{run['id']} failed {' '.join(command)} in isolated validation:\n{process.stdout}"
                )


def check_report_arithmetic(content: str, path: Path) -> None:
    values = extract_report_values(path, content)
    if (values["overhead"] is None) != (values["combined"] is None):
        raise BenchmarkError(f"Unknown overhead must have unknown combined usage in {path}")
    if values["overhead"] is not None and values["tested"] + values["overhead"] != values["combined"]:
        raise BenchmarkError(f"Combined total mismatch in {path}")
    for row in re.findall(r"^\|.*\|$", content, re.M):
        if "---" in row or "Input" in row or "Source" in row or "Phase" in row:
            continue
        cells = [cell.strip().replace("*", "").replace(",", "") for cell in row.strip("|").split("|")]
        numeric = []
        for cell in cells[-5:]:
            try:
                numeric.append(int(cell))
            except ValueError:
                numeric = []
                break
        if len(numeric) == 5 and sum(numeric[:4]) != numeric[4]:
            raise BenchmarkError(f"Token row mismatch in {path}: {row}")


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as handle:
            handle.write(content)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def show_diff(path: Path, content: str) -> None:
    old = path.read_text().splitlines(keepends=True) if path.exists() else []
    new = content.splitlines(keepends=True)
    sys.stdout.writelines(difflib.unified_diff(old, new, fromfile=str(path), tofile=str(path)))


def refresh(
    root: Path,
    runs: list[dict[str, Any]],
    ranking: dict[str, Any],
    pricing: dict[str, Any],
    selected: list[dict[str, Any]],
    codex_home: Path,
    omp_home: Path,
    pi_home: Path,
    t3_home: Path,
    dry_run: bool,
) -> None:
    results: dict[str, RunResult] = {}
    reports: dict[str, str] = {}
    for run in selected:
        print(f"Collecting {run['label']}...", file=sys.stderr)
        result = collect_run(run, codex_home, omp_home, pi_home, t3_home)
        validate_project(root, run)
        report = render_statistics(result)
        path = root / run["project_dir"] / "STATISTICS.md"
        check_report_arithmetic(report, path)
        results[run["id"]] = result
        reports[run["id"]] = report
    documents = render_documents(root, runs, reports, ranking, pricing)
    if dry_run:
        for run in selected:
            show_diff(root / run["project_dir"] / "STATISTICS.md", reports[run["id"]])
        for path, content in documents.items():
            show_diff(path, content)
        return
    for run in selected:
        atomic_write(root / run["project_dir"] / "STATISTICS.md", reports[run["id"]])
    for path, content in documents.items():
        atomic_write(path, content)


def site_results(
    root: Path, runs: list[dict[str, Any]], ranking: dict[str, Any], pricing: dict[str, Any],
) -> dict[str, Any]:
    ranked = {entry["run_id"]: (rank, entry, score) for rank, entry, score in ranked_entries(ranking)}
    records = []
    for run in runs:
        values = extract_report_values(root / run["project_dir"] / "STATISTICS.md")
        record: dict[str, Any] = {
            "id": run["id"],
            "label": run["label"],
            "project_dir": run["project_dir"],
            "model": run["model"],
            "effort": run.get("reasoning_variant"),
            "web": run.get("web", "open"),
            "harness_label": run["harness_label"],
            "tokens": {**values["tested_usage"], "total": values["tested"]},
            "elapsed": values["elapsed"],
            "elapsed_ms": values["elapsed_ms"],
            "tool_calls": values["tool_calls"],
            "model_responses": values["model_responses"],
            "overhead_verified": values["overhead"] is not None,
            "comparison_note": run.get("comparison_note"),
            "known_browser_failure": run.get("known_browser_failure"),
            "static_aliases": run.get("static_aliases", {}),
            "cost": estimate_cost(values["tested_usage"], pricing["models"][run["model"]]),
            "price": pricing["models"][run["model"]],
            "rank": None,
        }
        if run["id"] in ranked:
            rank, entry, score = ranked[run["id"]]
            record.update({
                "rank": rank,
                "score": float(score),
                "score_text": str(score),
                "scores": entry["scores"],
                "bugs": entry["bugs"],
                "bug_counts": bug_counts(entry),
                "summary": entry["summary"],
                "audited": entry["audited"],
            })
        records.append(record)
    records.sort(key=lambda record: (record["rank"] is None, record["rank"] or 0))
    return {
        "criteria": [{"key": key, "label": label, "weight": ranking["weights"][key]} for key, label in CRITERIA],
        "pricing_basis": pricing["basis"],
        "runs": records,
    }


