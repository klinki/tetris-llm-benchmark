def load_manifest(root: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    path = root / "benchmark-runs.json"
    try:
        manifest = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise BenchmarkError(f"Cannot read {path}: {error}") from error
    if manifest.get("schema_version") != 1:
        raise BenchmarkError("Unsupported benchmark-runs.json schema_version")
    if manifest.get("generator_version") != GENERATOR_VERSION:
        raise BenchmarkError("Manifest generator_version does not match the CLI")
    runs = manifest.get("runs")
    if not isinstance(runs, list) or not runs:
        raise BenchmarkError("Manifest must contain a non-empty runs array")
    ids: set[str] = set()
    orders: set[int] = set()
    required = {
        "id", "label", "order", "project_dir", "harness", "harness_label",
        "provider", "provider_label", "model", "session_id",
        "expected_cwd_basename", "cutoff", "overhead",
    }
    for run in runs:
        missing = required - set(run)
        if missing:
            raise BenchmarkError(f"Run {run.get('id', '<unknown>')} missing {sorted(missing)}")
        if run["id"] in ids or run["order"] in orders:
            raise BenchmarkError("Run IDs and display orders must be unique")
        if run["harness"] not in {"codex", "omp", "pi", *T3_HARNESSES}:
            raise BenchmarkError(f"Unsupported harness for {run['id']}: {run['harness']}")
        through = run["cutoff"].get("through_user_message")
        if not isinstance(through, int) or through < 1:
            raise BenchmarkError(f"Invalid cutoff for {run['id']}")
        if run["harness"] in T3_HARNESSES:
            if not {"t3_thread_id", "expected_cwd", "reasoning_variant"} <= set(run):
                raise BenchmarkError(f"Missing T3 thread, exact cwd, or reasoning variant for {run['id']}")
            if run["overhead"].get("kind") != "unknown":
                raise BenchmarkError(f"T3 overhead must explicitly be unknown for {run['id']}")
        aliases = run.get("static_aliases", {})
        if not isinstance(aliases, dict) or not all(
            isinstance(alias, str) and isinstance(source, str) and alias and source
            for alias, source in aliases.items()
        ):
            raise BenchmarkError(f"static_aliases for {run['id']} must map file paths to file paths")
        if run.get("web", "open") not in t3_runs.WEB_MODES:
            raise BenchmarkError(f"web for {run['id']} must be one of {list(t3_runs.WEB_MODES)}")
        if not isinstance(run.get("known_browser_failure", ""), str):
            raise BenchmarkError(f"known_browser_failure for {run['id']} must be a description")
        ids.add(run["id"])
        orders.add(run["order"])
    return manifest, sorted(runs, key=lambda item: item["order"])


def load_ranking(root: Path, runs: list[dict[str, Any]]) -> dict[str, Any]:
    path = root / "ranking.json"
    try:
        ranking = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise BenchmarkError(f"Cannot read {path}: {error}") from error
    if ranking.get("schema_version") != 1:
        raise BenchmarkError("Unsupported ranking.json schema_version")
    criteria = {key for key, _ in CRITERIA}
    weights = ranking.get("weights")
    if (
        not isinstance(weights, dict)
        or set(weights) != criteria
        or any(not isinstance(value, int) or value < 0 for value in weights.values())
        or sum(weights.values()) != 100
    ):
        raise BenchmarkError("ranking.json weights must be integer percentages for every criterion summing to 100")
    known = {run["id"] for run in runs}
    seen: set[str] = set()
    entries = ranking.get("entries")
    if not isinstance(entries, list):
        raise BenchmarkError("ranking.json must contain an entries array")
    for entry in entries:
        run_id = entry.get("run_id")
        if run_id not in known:
            raise BenchmarkError(f"ranking.json scores unregistered run: {run_id}")
        if run_id in seen:
            raise BenchmarkError(f"ranking.json scores {run_id} more than once")
        seen.add(run_id)
        scores = entry.get("scores")
        if not isinstance(scores, dict) or set(scores) != criteria:
            raise BenchmarkError(f"ranking.json entry {run_id} must score exactly {sorted(criteria)}")
        for value in scores.values():
            if (
                isinstance(value, bool)
                or not isinstance(value, (int, float))
                or not 0 <= value <= 10
                or value * 2 != int(value * 2)
            ):
                raise BenchmarkError(f"ranking.json entry {run_id} has a score that is not a 0-10 half point")
        bugs = entry.get("bugs")
        if not isinstance(bugs, list) or any(
            not isinstance(bug, dict)
            or set(bug) != {"severity", "title", "detail"}
            or bug["severity"] not in BUG_KINDS
            or not bug["title"]
            or not bug["detail"]
            for bug in bugs
        ):
            raise BenchmarkError(
                f"ranking.json entry {run_id} bugs need a severity in {list(BUG_KINDS)}, a title, and a detail"
            )
        if not entry.get("summary") or "|" in entry["summary"] or not entry.get("audited"):
            raise BenchmarkError(f"ranking.json entry {run_id} needs an audit date and a summary without '|'")
    return ranking


def load_pricing(root: Path, runs: list[dict[str, Any]]) -> dict[str, Any]:
    path = root / "pricing.json"
    try:
        pricing = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise BenchmarkError(f"Cannot read {path}: {error}") from error
    if pricing.get("schema_version") != 1:
        raise BenchmarkError("Unsupported pricing.json schema_version")
    models = pricing.get("models")
    if not isinstance(models, dict):
        raise BenchmarkError("pricing.json must contain a models object")
    for model, entry in models.items():
        if not entry.get("label"):
            raise BenchmarkError(f"pricing.json entry {model} needs a label")
        if "unpriced" in entry:
            if not entry["unpriced"] or "prices" in entry:
                raise BenchmarkError(f"pricing.json entry {model} must either give prices or say why it is unpriced")
            continue
        prices = entry.get("prices")
        if (
            not isinstance(prices, dict)
            or set(prices) != set(TOKEN_KINDS)
            or any(prices[kind] is None for kind in ("input", "cache_read", "output"))
            or any(
                value is not None and (isinstance(value, bool) or not isinstance(value, (int, float)) or value < 0)
                for value in prices.values()
            )
        ):
            raise BenchmarkError(
                f"pricing.json entry {model} needs non-negative {list(TOKEN_KINDS)} prices; only cache_write may be null"
            )
        if entry.get("evidence") not in PRICE_EVIDENCE or not entry.get("source"):
            raise BenchmarkError(f"pricing.json entry {model} needs a source and evidence in {list(PRICE_EVIDENCE)}")
    for run in runs:
        if run["model"] not in models:
            raise BenchmarkError(f"pricing.json has no entry for {run['model']} (run {run['id']})")
    return pricing


def estimate_cost(tokens: dict[str, int], entry: dict[str, Any]) -> dict[str, Any] | None:
    if "unpriced" in entry:
        return None
    parts = {}
    for kind in TOKEN_KINDS:
        price = entry["prices"][kind]
        if tokens[kind] and price is None:
            raise BenchmarkError(f"{entry['label']} has {kind} tokens but pricing.json gives no {kind} price")
        parts[kind] = tokens[kind] * (price or 0) / 1_000_000
    return {"total": sum(parts.values()), "parts": parts}


def format_cost(cost: dict[str, Any] | None) -> str:
    if cost is None:
        return "—"
    return "<$0.01" if cost["total"] < 0.005 else f"${cost['total']:,.2f}"


def bug_counts(entry: dict[str, Any]) -> dict[str, int]:
    return {kind: sum(bug["severity"] == kind for bug in entry["bugs"]) for kind in BUG_KINDS}


def weighted_score(entry: dict[str, Any], weights: dict[str, int]) -> Decimal:
    # Half-point scores times integer percentages keep the weighted sum exact.
    half_points = sum(int(entry["scores"][key] * 2) * weights[key] for key, _ in CRITERIA)
    return (Decimal(half_points) / 200).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def ranked_entries(ranking: dict[str, Any]) -> list[tuple[int, dict[str, Any], Decimal]]:
    scored = [(entry, weighted_score(entry, ranking["weights"])) for entry in ranking["entries"]]
    scored.sort(key=lambda item: (
        item[1], item[0]["scores"]["correctness"], item[0]["scores"]["tests"], item[0]["scores"]["code"],
    ), reverse=True)
    return [(rank, entry, score) for rank, (entry, score) in enumerate(scored, start=1)]


def parse_iso_ms(value: str) -> float:
    try:
        return dt.datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp() * 1000
    except ValueError as error:
        raise BenchmarkError(f"Invalid ISO timestamp: {value}") from error


def iso_ms(value: float) -> str:
    timestamp = dt.datetime.fromtimestamp(value / 1000, tz=dt.timezone.utc)
    milliseconds = int(round(timestamp.microsecond / 1000))
    if milliseconds == 1000:
        timestamp += dt.timedelta(seconds=1)
        milliseconds = 0
    return timestamp.strftime("%Y-%m-%dT%H:%M:%S") + f".{milliseconds:03d}Z"


def duration(value_ms: float) -> str:
    milliseconds = int(round(value_ms))
    hours, remainder = divmod(milliseconds, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    seconds = remainder / 1000
    if hours:
        return f"{hours}h {minutes}m {seconds:.3f}s"
    if minutes:
        return f"{minutes}m {seconds:.3f}s"
    return f"{seconds:.3f}s"


def parse_duration(value: str) -> int:
    match = re.fullmatch(r"(?:(\d+)h )?(?:(\d+)m )?(\d+(?:\.\d+)?)s", value.strip())
    if not match:
        raise BenchmarkError(f"Invalid duration: {value}")
    hours, minutes, seconds = match.groups()
    return int(hours or 0) * 3_600_000 + int(minutes or 0) * 60_000 + round(float(seconds) * 1000)


def markdown_duration(value_ms: float) -> str:
    return duration(value_ms)


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    try:
        with path.open() as handle:
            for number, line in enumerate(handle, 1):
                if not line.strip():
                    continue
                try:
                    entries.append(json.loads(line))
                except json.JSONDecodeError as error:
                    raise BenchmarkError(f"Malformed JSON in {path}:{number}: {error}") from error
    except OSError as error:
        raise BenchmarkError(f"Cannot read {path}: {error}") from error
    return entries


def find_exact_session(base: Path, session_id: str, suffix: str = ".jsonl") -> Path:
    if not base.exists():
        raise BenchmarkError(f"Session root does not exist: {base}")
    matches = [path for path in base.rglob(f"*{session_id}*{suffix}") if path.is_file()]
    if len(matches) != 1:
        raise BenchmarkError(
            f"Expected exactly one session for {session_id} under {base}, found {len(matches)}"
        )
    return matches[0]


def usage_from_codex(raw: dict[str, Any]) -> Usage:
    input_with_cache = int(raw.get("input_tokens", 0))
    cache_read = int(raw.get("cached_input_tokens", 0))
    usage = Usage(
        input=input_with_cache - cache_read,
        cache_read=cache_read,
        cache_write=int(raw.get("cache_write_input_tokens", 0)),
        output=int(raw.get("output_tokens", 0)),
        total=int(raw.get("total_tokens", 0)),
    )
    usage.validate("Codex usage")
    return usage


def final_token_event(entries: list[dict[str, Any]], end_index: int) -> dict[str, Any]:
    events = [
        entry for entry in entries[: end_index + 1]
        if entry.get("type") == "event_msg"
        and entry.get("payload", {}).get("type") == "token_count"
        and entry.get("payload", {}).get("info") is not None
    ]
    if not events:
        raise BenchmarkError("No cumulative Codex token_count before the selected completion")
    return events[-1]


def collect_codex(run: dict[str, Any], codex_home: Path) -> RunResult:
    root_path = find_exact_session(codex_home / "sessions", run["session_id"])
    entries = read_jsonl(root_path)
    metas = [entry for entry in entries if entry.get("type") == "session_meta"]
    if len(metas) != 1:
        raise BenchmarkError(f"Codex root {run['id']} must contain one session_meta")
    meta = metas[0]["payload"]
    if meta.get("id") != run["session_id"] or meta.get("model_provider") != run["provider"]:
        raise BenchmarkError(f"Codex session identity/provider mismatch for {run['id']}")
    if Path(meta.get("cwd", "")).name != run["expected_cwd_basename"]:
        raise BenchmarkError(f"Codex cwd mismatch for {run['id']}: {meta.get('cwd')}")
    models = {
        entry.get("payload", {}).get("model")
        for entry in entries if entry.get("type") == "turn_context"
    } - {None}
    if models != {run["model"]}:
        raise BenchmarkError(f"Codex model mismatch for {run['id']}: {sorted(models)}")

    user_indices = [
        index for index, entry in enumerate(entries)
        if entry.get("type") == "event_msg" and entry.get("payload", {}).get("type") == "user_message"
    ]
    if not user_indices:
        raise BenchmarkError(f"No Codex user messages for {run['id']}")
    phases: list[Phase] = []
    previous_usage = Usage()
    raw_phase_events: list[dict[str, Any]] = []
    cursor = 0
    for number, start_index in enumerate(user_indices, 1):
        if start_index < cursor:
            continue
        end_candidates = [
            index for index in range(start_index, len(entries))
            if entries[index].get("type") == "event_msg"
            and entries[index].get("payload", {}).get("type") == "task_complete"
        ]
        if not end_candidates:
            raise BenchmarkError(f"Codex user message {number} has no task_complete")
        end_index = end_candidates[0]
        token_event = final_token_event(entries, end_index)
        cumulative = usage_from_codex(token_event["payload"]["info"]["total_token_usage"])
        phase_usage = cumulative - previous_usage
        phase_usage.validate(f"Codex phase {number}")
        segment = entries[start_index : end_index + 1]
        calls = [
            entry for entry in segment if entry.get("type") == "response_item"
            and entry.get("payload", {}).get("type") in {"custom_tool_call", "function_call"}
        ]
        results = [
            entry for entry in segment if entry.get("type") == "response_item"
            and entry.get("payload", {}).get("type") in {"custom_tool_call_output", "function_call_output"}
        ]
        tool_types: dict[str, int] = {}
        for call in calls:
            name = call.get("payload", {}).get("name", "unknown")
            tool_types[name] = tool_types.get(name, 0) + 1
        phases.append(Phase(
            number=number,
            start_ms=parse_iso_ms(entries[start_index]["timestamp"]),
            end_ms=parse_iso_ms(entries[end_index]["timestamp"]),
            usage=phase_usage,
            responses=0,
            assistant_messages=sum(
                entry.get("type") == "event_msg"
                and entry.get("payload", {}).get("type") == "agent_message"
                for entry in segment
            ),
            tool_calls=len(calls),
            tool_results=len(results),
            model_errors=sum(
                entry.get("type") == "event_msg"
                and entry.get("payload", {}).get("type") in {"stream_error", "error"}
                for entry in segment
            ),
            tool_errors=0,
            tool_types=tool_types,
        ))
        raw_phase_events.append(token_event)
        previous_usage = cumulative
        cursor = end_index + 1

    through = run["cutoff"]["through_user_message"]
    if through > len(phases):
        raise BenchmarkError(f"Cutoff for {run['id']} exceeds its {len(phases)} phases")
    included = phases[:through]
    tested = sum((phase.usage for phase in included), Usage())

    overhead = Usage()
    raw_overhead: list[dict[str, Any]] = []
    overhead_config = run["overhead"]
    if overhead_config["kind"] == "codex_guardian":
        ids = overhead_config.get("session_ids", [])
        if not ids:
            raise BenchmarkError(f"No guardian session IDs configured for {run['id']}")
        for session_id in ids:
            guardian_path = find_exact_session(codex_home / "sessions", session_id)
            guardian_entries = read_jsonl(guardian_path)
            guardian_meta = next(
                (entry.get("payload") for entry in guardian_entries if entry.get("type") == "session_meta"),
                None,
            )
            if not guardian_meta or guardian_meta.get("parent_thread_id") != run["session_id"]:
                raise BenchmarkError(f"Guardian {session_id} does not belong to {run['session_id']}")
            completion_indices = [
                index for index, entry in enumerate(guardian_entries)
                if entry.get("type") == "event_msg"
                and entry.get("payload", {}).get("type") == "task_complete"
                and parse_iso_ms(entry["timestamp"]) <= included[-1].end_ms
            ]
            if not completion_indices:
                raise BenchmarkError(f"Guardian {session_id} has no completion before cutoff")
            event = final_token_event(guardian_entries, completion_indices[-1])
            raw_overhead.append(event)
            overhead += usage_from_codex(event["payload"]["info"]["total_token_usage"])
        overhead_label = "Guardian" if len(ids) == 1 else f"Guardians ({len(ids)} rollouts)"
        overhead_count = len(ids)
    elif overhead_config["kind"] == "none":
        overhead_label = "None declared"
        overhead_count = 0
    else:
        raise BenchmarkError(f"Invalid Codex overhead kind for {run['id']}")

    tested.validate("Tested agent")
    overhead.validate("Harness overhead")
    combined = tested + overhead
    combined.validate("Combined")
    return RunResult(
        run=run,
        session_file=str(root_path),
        phases=phases,
        included_phases=included,
        tested=tested,
        overhead=overhead,
        combined=combined,
        overhead_label=overhead_label,
        overhead_count=overhead_count,
        raw_tested_events=[raw_phase_events[through - 1]],
        raw_overhead_events=raw_overhead,
        average_duration_ms=0,
    )


def open_omp_database(path: Path) -> sqlite3.Connection:
    if not path.exists():
        raise BenchmarkError(f"OMP stats database does not exist: {path}")
    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    required = {
        "messages": {"session_file", "timestamp", "duration", "input_tokens", "output_tokens", "cache_read_tokens", "cache_write_tokens", "total_tokens", "cost_total", "model", "provider", "error_message"},
        "user_messages": {"session_file", "timestamp"},
        "tool_calls": {"session_file", "timestamp", "tool_name", "result_chars", "is_error"},
    }
    for table, columns in required.items():
        actual = {row[1] for row in connection.execute(f"PRAGMA table_info({table})")}
        if not columns <= actual:
            connection.close()
            raise BenchmarkError(f"Unsupported OMP schema: {table} missing {sorted(columns - actual)}")
    return connection


def omp_phase_number(timestamp_ms: float, user_starts: list[float]) -> int:
    phase = 0
    for index, start in enumerate(user_starts, 1):
        if timestamp_ms >= (int(start) // 1000) * 1000:
            phase = index
        else:
            break
    return phase


def collect_omp(run: dict[str, Any], omp_home: Path) -> RunResult:
    connection = open_omp_database(omp_home / "stats.db")
    try:
        session_rows = connection.execute(
            "SELECT DISTINCT session_file, folder, model, provider FROM messages WHERE session_file LIKE ?",
            (f"%{run['session_id']}%",),
        ).fetchall()
        if len(session_rows) != 1:
            raise BenchmarkError(
                f"Expected one OMP session for {run['session_id']}, found {len(session_rows)}"
            )
        identity = session_rows[0]
        session_file = identity["session_file"]
        if identity["model"] != run["model"] or identity["provider"] != run["provider"]:
            raise BenchmarkError(f"OMP provider/model mismatch for {run['id']}")
        if run["expected_cwd_basename"] not in session_file and not identity["folder"].endswith(run["expected_cwd_basename"]):
            raise BenchmarkError(f"OMP folder mismatch for {run['id']}: {identity['folder']}")
        users = connection.execute(
            "SELECT timestamp FROM user_messages WHERE session_file=? ORDER BY timestamp",
            (session_file,),
        ).fetchall()
        user_starts = [float(row["timestamp"]) for row in users]
        if not user_starts:
            raise BenchmarkError(f"No OMP user messages for {run['id']}")
        message_rows = connection.execute(
            "SELECT * FROM messages WHERE session_file=? ORDER BY timestamp",
            (session_file,),
        ).fetchall()
        tool_rows = connection.execute(
            "SELECT * FROM tool_calls WHERE session_file=? ORDER BY timestamp",
            (session_file,),
        ).fetchall()
        phases: list[Phase] = []
        for number, start_ms in enumerate(user_starts, 1):
            messages = [row for row in message_rows if omp_phase_number(row["timestamp"], user_starts) == number]
            tools = [row for row in tool_rows if omp_phase_number(row["timestamp"], user_starts) == number]
            if not messages:
                raise BenchmarkError(f"OMP user message {number} has no model response")
            usage = Usage(
                input=sum(row["input_tokens"] for row in messages),
                cache_read=sum(row["cache_read_tokens"] for row in messages),
                cache_write=sum(row["cache_write_tokens"] for row in messages),
                output=sum(row["output_tokens"] for row in messages),
                total=sum(row["total_tokens"] for row in messages),
                cost=sum(row["cost_total"] for row in messages),
            )
            usage.validate(f"OMP phase {number}")
            tool_types: dict[str, int] = {}
            for tool in tools:
                tool_types[tool["tool_name"]] = tool_types.get(tool["tool_name"], 0) + 1
            phases.append(Phase(
                number=number,
                start_ms=start_ms,
                end_ms=max(row["timestamp"] + (row["duration"] or 0) for row in messages),
                usage=usage,
                responses=len(messages),
                assistant_messages=0,
                tool_calls=len(tools),
                tool_results=sum(row["result_chars"] is not None for row in tools),
                model_errors=sum(bool(row["error_message"]) for row in messages),
                tool_errors=sum(row["is_error"] == 1 for row in tools),
                tool_types=tool_types,
            ))
    finally:
        connection.close()

    through = run["cutoff"]["through_user_message"]
    if through > len(phases):
        raise BenchmarkError(f"Cutoff for {run['id']} exceeds its {len(phases)} phases")
    included = phases[:through]
    tested = sum((phase.usage for phase in included), Usage())
    included_response_count = sum(phase.responses for phase in included)
    included_duration = 0.0
    connection = open_omp_database(omp_home / "stats.db")
    try:
        rows = connection.execute(
            "SELECT timestamp, duration FROM messages WHERE session_file=? ORDER BY timestamp",
            (session_file,),
        ).fetchall()
        included_duration = sum(
            row["duration"] or 0 for row in rows
            if 1 <= omp_phase_number(row["timestamp"], user_starts) <= through
        )
    finally:
        connection.close()

    overhead_config = run["overhead"]
    raw_overhead: list[dict[str, Any]] = []
    overhead = Usage()
    if overhead_config["kind"] == "omp_titles":
        seen: set[tuple[Any, ...]] = set()
        for path in sorted((omp_home / "logs").glob("*.log")):
            for entry in read_jsonl(path):
                if entry.get("sessionId") != run["session_id"] or entry.get("message") != "title-generator: success":
                    continue
                if parse_iso_ms(entry["timestamp"]) > included[-1].end_ms:
                    continue
                raw = entry.get("usage", {})
                key = (
                    entry.get("timestamp"), raw.get("input"), raw.get("output"),
                    raw.get("cacheRead"), raw.get("cacheWrite"), raw.get("totalTokens"),
                )
                if key in seen:
                    continue
                seen.add(key)
                raw_overhead.append(entry)
                title_usage = Usage(
                    input=int(raw.get("input", 0)),
                    cache_read=int(raw.get("cacheRead", 0)),
                    cache_write=int(raw.get("cacheWrite", 0)),
                    output=int(raw.get("output", 0)),
                    total=int(raw.get("totalTokens", 0)),
                    cost=float(raw.get("cost", {}).get("total", 0)),
                )
                title_usage.validate("OMP title usage")
                overhead += title_usage
        expected = overhead_config.get("expected_count")
        if len(raw_overhead) != expected:
            raise BenchmarkError(
                f"Expected {expected} title events for {run['id']}, found {len(raw_overhead)}"
            )
        overhead_label = f"Title generation ({expected} requests)"
        overhead_count = expected
    elif overhead_config["kind"] == "none":
        overhead_label = "None declared"
        overhead_count = 0
    else:
        raise BenchmarkError(f"Invalid OMP overhead kind for {run['id']}")

    tested.validate("Tested agent")
    overhead.validate("Harness overhead")
    combined = tested + overhead
    combined.validate("Combined")
    return RunResult(
        run=run,
        session_file=session_file,
        phases=phases,
        included_phases=included,
        tested=tested,
        overhead=overhead,
        combined=combined,
        overhead_label=overhead_label,
        overhead_count=overhead_count,
        raw_tested_events=[],
        raw_overhead_events=raw_overhead,
        average_duration_ms=included_duration / included_response_count,
    )


def usage_from_pi(raw: dict[str, Any]) -> Usage:
    required = {"input", "cacheRead", "cacheWrite", "output", "reasoning", "totalTokens", "cost"}
    missing = required - set(raw)
    if missing or not isinstance(raw.get("cost"), dict) or "total" not in raw["cost"]:
        raise BenchmarkError(f"Unsupported PI usage schema; missing {sorted(missing)} or cost.total")
    usage = Usage(
        input=int(raw.get("input", 0)),
        cache_read=int(raw.get("cacheRead", 0)),
        cache_write=int(raw.get("cacheWrite", 0)),
        output=int(raw.get("output", 0)),
        total=int(raw.get("totalTokens", 0)),
        cost=float(raw.get("cost", {}).get("total", 0)),
    )
    usage.validate("PI usage")
    reasoning = int(raw.get("reasoning", 0))
    if reasoning < 0 or reasoning > usage.output:
        raise BenchmarkError("PI reasoning tokens must be a non-negative subset of output")
    return usage


def collect_pi(run: dict[str, Any], pi_home: Path) -> RunResult:
    session_path = find_exact_session(pi_home / "agent" / "sessions", run["session_id"])
    entries = read_jsonl(session_path)
    sessions = [entry for entry in entries if entry.get("type") == "session"]
    if len(sessions) != 1:
        raise BenchmarkError(f"PI run {run['id']} must contain one session record")
    session = sessions[0]
    if session.get("version") != 3:
        raise BenchmarkError(f"Unsupported PI session version for {run['id']}: {session.get('version')}")
    if session.get("id") != run["session_id"]:
        raise BenchmarkError(f"PI session identity mismatch for {run['id']}")
    if Path(session.get("cwd", "")).name != run["expected_cwd_basename"]:
        raise BenchmarkError(f"PI cwd mismatch for {run['id']}: {session.get('cwd')}")

    message_entries = [entry for entry in entries if entry.get("type") == "message"]
    users = [
        (index, entry) for index, entry in enumerate(message_entries)
        if entry.get("message", {}).get("role") == "user"
    ]
    if not users:
        raise BenchmarkError(f"No PI user messages for {run['id']}")

    phases: list[Phase] = []
    phase_reasoning: list[int] = []
    phase_request_durations: list[float] = []
    for number, (start_index, user_entry) in enumerate(users, 1):
        end_index = users[number][0] if number < len(users) else len(message_entries)
        segment = message_entries[start_index + 1:end_index]
        assistants = [
            entry for entry in segment
            if entry.get("message", {}).get("role") == "assistant"
        ]
        if not assistants:
            raise BenchmarkError(f"PI user message {number} has no model response")
        if assistants[-1]["message"].get("stopReason") != "stop":
            raise BenchmarkError(f"PI user message {number} has no completed final response")
        identities = {
            (entry["message"].get("provider"), entry["message"].get("model"))
            for entry in assistants
        }
        if identities != {(run["provider"], run["model"])}:
            raise BenchmarkError(f"PI provider/model mismatch for {run['id']}: {sorted(identities)}")

        usage = sum(
            (usage_from_pi(entry["message"].get("usage", {})) for entry in assistants),
            Usage(),
        )
        phase_reasoning.append(sum(
            int(entry["message"].get("usage", {}).get("reasoning", 0))
            for entry in assistants
        ))
        tool_types: dict[str, int] = {}
        calls = []
        for entry in assistants:
            for content in entry["message"].get("content", []):
                if content.get("type") == "toolCall":
                    calls.append(content)
                    name = content.get("name", "unknown")
                    tool_types[name] = tool_types.get(name, 0) + 1
        results = [
            entry for entry in segment
            if entry.get("message", {}).get("role") == "toolResult"
        ]

        previous_ms = parse_iso_ms(user_entry["timestamp"])
        request_duration = 0.0
        for entry in segment:
            timestamp_ms = parse_iso_ms(entry["timestamp"])
            if entry.get("message", {}).get("role") == "assistant":
                request_duration += max(0, timestamp_ms - previous_ms)
            previous_ms = timestamp_ms
        phase_request_durations.append(request_duration)

        phases.append(Phase(
            number=number,
            start_ms=parse_iso_ms(user_entry["timestamp"]),
            end_ms=parse_iso_ms(assistants[-1]["timestamp"]),
            usage=usage,
            responses=len(assistants),
            assistant_messages=0,
            tool_calls=len(calls),
            tool_results=len(results),
            model_errors=sum(
                entry["message"].get("stopReason") in {"error", "aborted"}
                for entry in assistants
            ),
            tool_errors=sum(entry["message"].get("isError") is True for entry in results),
            tool_types=tool_types,
        ))

    through = run["cutoff"]["through_user_message"]
    if through > len(phases):
        raise BenchmarkError(f"Cutoff for {run['id']} exceeds its {len(phases)} phases")
    included = phases[:through]
    tested = sum((phase.usage for phase in included), Usage())

    overhead_config = run["overhead"]
    if overhead_config.get("kind") != "none":
        raise BenchmarkError(f"Invalid PI overhead kind for {run['id']}")
    overhead = Usage()
    combined = tested + overhead
    tested.validate("Tested agent")
    combined.validate("Combined")
    return RunResult(
        run=run,
        session_file=str(session_path),
        phases=phases,
        included_phases=included,
        tested=tested,
        overhead=overhead,
        combined=combined,
        overhead_label="None declared",
        overhead_count=0,
        raw_tested_events=[],
        raw_overhead_events=[],
        average_duration_ms=(
            sum(phase_request_durations[:through])
            / sum(phase.responses for phase in included)
        ),
        reasoning_output=sum(phase_reasoning[:through]),
    )


def usage_from_t3(raw: dict[str, Any]) -> Usage:
    required = {
        "inputTokens", "cachedInputTokens", "cacheCreationTokens", "outputTokens",
        "reasoningTokens", "usageStatus", "usageScope", "hasSubagents",
    }
    if not isinstance(raw, dict):
        raise BenchmarkError("Unsupported T3 usage schema: expected an object")
    if not required <= set(raw):
        raise BenchmarkError(f"Unsupported T3 usage schema: missing {sorted(required - set(raw))}")
    if raw["usageStatus"] != "complete" or raw["usageScope"] != "main_agent" or raw["hasSubagents"] is not False:
        raise BenchmarkError("T3 usage must be complete main-agent usage without subagents")
    for key in required - {"usageStatus", "usageScope", "hasSubagents"}:
        if type(raw[key]) is not int or raw[key] < 0:
            raise BenchmarkError(f"Invalid T3 token count: {key}")
    usage = Usage(
        input=raw["inputTokens"] - raw["cachedInputTokens"] - raw["cacheCreationTokens"],
        cache_read=raw["cachedInputTokens"],
        cache_write=raw["cacheCreationTokens"],
        output=raw["outputTokens"],
        total=raw["inputTokens"] + raw["outputTokens"],
    )
    usage.validate("T3 usage")
    if raw["reasoningTokens"] > usage.output:
        raise BenchmarkError("T3 reasoning tokens must be a subset of output")
    return usage


def validate_claude_effort(run: dict[str, Any], t3_home: Path) -> None:
    """Validate the effective SDK effort, which is absent from T3's model options."""
    paths = t3_runs.provider_logs(t3_home, run["t3_thread_id"])
    matched = 0
    for path in paths:
        for line in path.read_text().splitlines():
            if '"query.open"' not in line:
                continue
            try:
                record = json.loads(line[line.index("{"):])
                payload = record.get("event", {}).get("payload", {})
                options = payload.get("options", {})
            except (ValueError, TypeError, json.JSONDecodeError) as error:
                raise BenchmarkError(f"Unsupported Claude provider-log record in {path}") from error
            if payload.get("type") != "query.open" or options.get("sessionId") != run["session_id"]:
                continue
            if options.get("model") != run["model"] or options.get("cwd") != run["expected_cwd"]:
                raise BenchmarkError(f"Claude SDK request identity mismatch for {run['id']}")
            if options.get("effort") != run["reasoning_variant"]:
                raise BenchmarkError(f"Claude SDK effort mismatch for {run['id']}")
            if "fast_mode" in run and options.get("settings", {}).get("fastMode") != run["fast_mode"]:
                raise BenchmarkError(f"Claude SDK fast-mode mismatch for {run['id']}")
            matched += 1
    if not matched:
        raise BenchmarkError(f"No matching Claude SDK query.open effort evidence for {run['id']}")


def collect_t3_parent(
    run: dict[str, Any], t3_home: Path, app_thread: dict[str, Any], user_message: sqlite3.Row,
) -> list[dict[str, Any]]:
    parent = run["t3_parent"]
    sender = json.loads(user_message["payload_json"]).get("senderThreadId")
    if app_thread.get("lineage", {}).get("parentThreadId") != parent["thread_id"] or sender != parent["thread_id"]:
        raise BenchmarkError(f"T3 parent lineage mismatch for {run['id']}")
    database = t3_home / "userdata" / "statev2.sqlite"
    with closing(sqlite3.connect(database.resolve().as_uri() + "?mode=ro", uri=True)) as connection:
        connection.row_factory = sqlite3.Row
        rows = connection.execute("""
            SELECT pt.payload_json AS parent_json, u.payload_json AS turn_json,
                   u.status, u.completed_at, u.ordinal
            FROM orchestration_v2_projection_provider_threads pt
            JOIN orchestration_v2_projection_provider_turns u
              ON u.provider_thread_id=pt.provider_thread_id AND u.thread_id=pt.thread_id
            WHERE pt.thread_id=? AND pt.provider='opencode'
              AND json_extract(pt.payload_json, '$.nativeThreadRef.nativeId')=?
            ORDER BY u.ordinal
        """, (parent["thread_id"], parent["session_id"])).fetchall()
    if len(rows) != parent["expected_turns"]:
        raise BenchmarkError(f"Unexpected T3 parent-turn count for {run['id']}: {len(rows)}")
    events = []
    for row in rows:
        native = json.loads(row["parent_json"])
        selection = native.get("nativeMetadata", {}).get("modelSelection", {})
        variants = [option.get("value") for option in selection.get("options", []) if option.get("id") == "variant"]
        if selection.get("model") != parent["model_alias"] or variants != [parent["reasoning_variant"]]:
            raise BenchmarkError(f"T3 parent model/variant mismatch for {run['id']}")
        turn = json.loads(row["turn_json"])
        if row["status"] != "completed" or turn.get("status") != "completed":
            raise BenchmarkError(f"Incomplete T3 parent turn for {run['id']}")
        raw = turn.get("turnTokenUsage")
        usage_from_t3(raw)
        events.append({"ordinal": row["ordinal"], "completedAt": row["completed_at"], "turnTokenUsage": raw})
    return events


def validate_codex_effort(run: dict[str, Any], codex_home: Path) -> None:
    """Validate the model, effort, and cwd Codex recorded, which T3's model options do not prove."""
    try:
        context = t3_runs.codex_turn_context(codex_home, run["session_id"])
    except (t3_runs.RunError, OSError, KeyError, json.JSONDecodeError) as error:
        raise BenchmarkError(f"Codex rollout evidence for {run['id']}: {error}") from error
    if context["model"] != run["model"] or context["cwd"] != run["expected_cwd"]:
        raise BenchmarkError(f"Codex request identity mismatch for {run['id']}")
    if context["effort"] != run["reasoning_variant"]:
        raise BenchmarkError(f"Codex effort mismatch for {run['id']}")
    if context["service_tier"] in t3_runs.FAST_SERVICE_TIERS:
        raise BenchmarkError(f"Codex ran {run['id']} on the faster {context['service_tier']} service tier")


def collect_t3_opencode(run: dict[str, Any], t3_home: Path, codex_home: Path | None = None) -> RunResult:
    database = t3_home / "userdata" / "statev2.sqlite"
    if not database.is_file():
        raise BenchmarkError(f"T3 database does not exist: {database}")
    driver = {"t3_claude": "claudeAgent", "t3_codex": "codex"}.get(run["harness"], "opencode")
    # Claude and Codex threads keep their model selection on T3's application thread.
    uses_app_selection = driver in {"claudeAgent", "codex"}
    provider_instance = run.get("t3_provider_instance", driver)
    app_thread = None
    with closing(sqlite3.connect(database.resolve().as_uri() + "?mode=ro", uri=True)) as connection:
        connection.row_factory = sqlite3.Row
        try:
            records = connection.execute("""
                SELECT p.workspace_root, t.default_provider, pt.provider,
                       pt.payload_json AS provider_thread_json,
                       u.payload_json AS turn_json, u.status, u.completed_at,
                       u.provider_turn_id
                FROM orchestration_v2_projection_threads t
                JOIN projection_projects p ON p.project_id=t.project_id
                JOIN orchestration_v2_projection_provider_threads pt ON pt.thread_id=t.thread_id
                JOIN orchestration_v2_projection_provider_turns u
                  ON u.provider_thread_id=pt.provider_thread_id AND u.thread_id=t.thread_id
                WHERE t.thread_id=?
                  AND json_extract(pt.payload_json, '$.nativeThreadRef.nativeId')=?
                ORDER BY u.ordinal
            """, (run["t3_thread_id"], run["session_id"])).fetchall()
            messages = connection.execute("""
                SELECT role, created_at, payload_json
                FROM orchestration_v2_projection_messages
                WHERE thread_id=? ORDER BY created_at, message_id
            """, (run["t3_thread_id"],)).fetchall()
            if uses_app_selection or run.get("t3_parent"):
                app_rows = connection.execute(
                    "SELECT payload_json FROM orchestration_v2_projection_threads WHERE thread_id=?",
                    (run["t3_thread_id"],),
                ).fetchall()
                if len(app_rows) != 1:
                    raise BenchmarkError(f"Ambiguous T3 application thread for {run['id']}")
                app_thread = json.loads(app_rows[0]["payload_json"])
        except sqlite3.DatabaseError as error:
            raise BenchmarkError(f"Unsupported T3 database schema: {error}") from error
    # This adapter supports the audited single-prompt, single-provider-turn
    # schema. Fail explicitly rather than guessing at future multi-turn data.
    users = [message for message in messages if message["role"] == "user"]
    if len(records) != 1 or len(users) != 1 or run["cutoff"]["through_user_message"] != 1:
        raise BenchmarkError(
            f"Expected one T3 user message and provider turn for {run['id']}; "
            f"found {len(users)} messages and {len(records)} turns"
        )
    record = records[0]
    if record["workspace_root"] != run["expected_cwd"] or Path(record["workspace_root"]).name != run["expected_cwd_basename"]:
        raise BenchmarkError(f"T3 cwd mismatch for {run['id']}: {record['workspace_root']}")
    if record["default_provider"] != provider_instance or record["provider"] != provider_instance:
        raise BenchmarkError(f"T3 driver/provider mismatch for {run['id']}")
    try:
        provider_thread = json.loads(record["provider_thread_json"])
        turn = json.loads(record["turn_json"])
        selection = (app_thread["modelSelection"] if uses_app_selection
                     else provider_thread["nativeMetadata"]["modelSelection"])
        raw_usage = turn["turnTokenUsage"]
    except (KeyError, TypeError, json.JSONDecodeError) as error:
        raise BenchmarkError(f"Unsupported T3 record schema for {run['id']}") from error
    if not isinstance(selection, dict) or not isinstance(selection.get("options"), list):
        raise BenchmarkError(f"Unsupported T3 model-selection schema for {run['id']}")
    if any(not isinstance(option, dict) for option in selection["options"]):
        raise BenchmarkError(f"Unsupported T3 model options for {run['id']}")
    model = run["model"] if uses_app_selection else f"{run['provider']}/{run['model']}"
    if selection.get("model") != model:
        raise BenchmarkError(f"T3 provider/model mismatch for {run['id']}")
    if driver == "claudeAgent":
        validate_claude_effort(run, t3_home)
    elif driver == "codex":
        validate_codex_effort(run, codex_home or t3_runs.codex_home())
    else:
        variants = [option.get("value") for option in selection.get("options", []) if option.get("id") == "variant"]
        if variants != [run["reasoning_variant"]]:
            raise BenchmarkError(f"T3 reasoning variant mismatch for {run['id']}: {variants}")
    if record["status"] != "completed" or turn.get("status") != "completed" or not record["completed_at"]:
        raise BenchmarkError(f"T3 turn has no completed response for {run['id']}")
    if run["overhead"].get("kind") != "unknown":
        raise BenchmarkError(f"T3 overhead must explicitly be unknown for {run['id']}")
    if run.get("expected_task_cwd"):
        prompt = json.loads(users[0]["payload_json"]).get("text", "")
        if run["expected_task_cwd"] not in prompt:
            raise BenchmarkError(f"T3 delegated working-directory instruction mismatch for {run['id']}")
    start_ms = parse_iso_ms(users[0]["created_at"])
    end_ms = parse_iso_ms(record["completed_at"])
    if end_ms < start_ms:
        raise BenchmarkError(f"T3 response ends before the user message for {run['id']}")
    tested = usage_from_t3(raw_usage)
    phase = Phase(
        number=1, start_ms=start_ms, end_ms=end_ms, usage=tested,
        responses=0, assistant_messages=sum(message["role"] == "assistant" for message in messages),
        tool_calls=0, tool_results=0, model_errors=0, tool_errors=0, tool_types={},
    )
    parent_events = collect_t3_parent(run, t3_home, app_thread, users[0]) if run.get("t3_parent") else []
    return RunResult(
        run=run, session_file=str(database), phases=[phase], included_phases=[phase],
        tested=tested, overhead=None, combined=None, overhead_label="Not verified",
        overhead_count=0, raw_tested_events=[{"turnTokenUsage": raw_usage}],
        raw_overhead_events=parent_events, average_duration_ms=0,
        reasoning_output=raw_usage["reasoningTokens"],
    )


def collect_run(
    run: dict[str, Any], codex_home: Path, omp_home: Path, pi_home: Path,
    t3_home: Path,
) -> RunResult:
    if run["harness"] == "codex":
        return collect_codex(run, codex_home)
    if run["harness"] == "omp":
        return collect_omp(run, omp_home)
    if run["harness"] == "pi":
        return collect_pi(run, pi_home)
    if run["harness"] in T3_HARNESSES:
        return collect_t3_opencode(run, t3_home, codex_home)
    raise BenchmarkError(f"Unsupported harness: {run['harness']}")


def usage_row(usage: Usage | None, bold_total: bool = True) -> str:
    if usage is None:
        return "| Not verified | Not verified | Not verified | Not verified | Not verified |"
    total = f"**{usage.total:,}**" if bold_total else f"{usage.total:,}"
    return (
        f"| {usage.input:,} | {usage.cache_read:,} | {usage.cache_write:,} | "
        f"{usage.output:,} | {total} |"
    )


def phase_label(run: dict[str, Any], phase: Phase) -> str:
    labels = run.get("phase_labels", [])
    if phase.number <= len(labels):
        return labels[phase.number - 1]
    return f"Message {phase.number}"


