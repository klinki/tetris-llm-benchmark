const O_WALL_KICKS: readonly Point[] = [{ x: 0, y: 0 }];

/**
 * Returns the 5 SRS wall kick test offsets for a given piece type and rotation transition.
 */
export function getWallKicks(
  type: TetrominoType,
  fromRotation: RotationState,
  toRotation: RotationState
): readonly Point[] {
  if (type === 'O') {
    return O_WALL_KICKS;
  }
  const key = `${fromRotation}->${toRotation}`;
  if (type === 'I') {
    return I_WALL_KICKS[key] ?? O_WALL_KICKS;
  }
  return JLSTZ_WALL_KICKS[key] ?? O_WALL_KICKS;
}

/**
 * Returns the board coordinates of all 4 minoes of a piece at (x, y, rotation).
 */
export function getPieceCells(
  type: TetrominoType,
  x: number,
  y: number,
  rotation: RotationState = 0
): Point[] {
  return SHAPES[type][rotation].map((offset) => ({
    x: x + offset.x,
    y: y + offset.y,
  }));
}
