const TABLES: Record<PieceType, Record<string, readonly Kick[]>> = {
  I: I_TABLE,
  J: JLSTZ_TABLE,
  L: JLSTZ_TABLE,
  O: O_TABLE,
  S: JLSTZ_TABLE,
  T: JLSTZ_TABLE,
  Z: JLSTZ_TABLE,
};

/** Returns the wall kick offsets for a rotation from `from` to `to`. */
export function getKicks(type: PieceType, from: number, to: number): readonly Kick[] {
  const table = TABLES[type];
  return table[`${from}>${to}`] ?? [[0, 0]];
}
