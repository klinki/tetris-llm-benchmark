/** Kick candidates for rotating `type` from state `from` to `to`, in order. */
export function kicksFor(type: Tetromino, from: Rotation, to: Rotation): [number, number][] {
  if (type === 'O') return [[0, 0]];
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  return table[`${from}-${to}`];
}
