import { SPAWN_ROW } from './constants.js';

export type PieceType = 'I' | 'O' | 'T' | 'S' | 'Z' | 'J' | 'L';

/** 0 = spawn, 1 = clockwise, 2 = half turn, 3 = counter-clockwise. */
export type Rotation = 0 | 1 | 2 | 3;

/** A cell offset [x, y] inside a piece's shape box, or a kick offset. */
export type Offset = readonly [x: number, y: number];

/** Where a piece is: its type, orientation, and the top-left corner of its shape box. */
export interface PieceState {
  readonly type: PieceType;
  readonly rotation: Rotation;
  readonly x: number;
  readonly y: number;
}

type Shape = readonly [Offset[], Offset[], Offset[], Offset[]];

interface PieceDef {
  readonly color: string;
  /** Left column of the shape box when the piece spawns. */
  readonly spawnX: number;
  /** Filled cells for each rotation state. */
  readonly shapes: Shape;
}

export const PIECE_TYPES: readonly PieceType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

/**
 * Shapes are written as they appear in the spawn orientation ('X' = filled).
 * The other rotation states are generated by turning the spawn shape clockwise.
 */
export const PIECES: Record<PieceType, PieceDef> = {
  I: { color: '#00e5ff', spawnX: 3, shapes: buildShapes(['....', 'XXXX', '....', '....']) },
  O: { color: '#ffd400', spawnX: 4, shapes: buildShapes(['XX', 'XX']) },
  T: { color: '#b56cff', spawnX: 3, shapes: buildShapes(['.X.', 'XXX', '...']) },
  S: { color: '#3ddc84', spawnX: 3, shapes: buildShapes(['.XX', 'XX.', '...']) },
  Z: { color: '#ff4d5e', spawnX: 3, shapes: buildShapes(['XX.', '.XX', '...']) },
  J: { color: '#3b82ff', spawnX: 3, shapes: buildShapes(['X..', 'XXX', '...']) },
  L: { color: '#ff9f1c', spawnX: 3, shapes: buildShapes(['..X', 'XXX', '...']) },
};

/** Filled cells of a piece in the given rotation, relative to its shape box. */
export function offsetsOf(type: PieceType, rotation: Rotation): readonly Offset[] {
  return PIECES[type].shapes[rotation];
}

/** A piece in its spawn orientation at its spawn position. */
export function spawnPiece(type: PieceType): PieceState {
  return { type, rotation: 0, x: PIECES[type].spawnX, y: SPAWN_ROW };
}

function buildShapes(spawn: readonly string[]): Shape {
  const second = rotateClockwise(spawn);
  const third = rotateClockwise(second);
  const fourth = rotateClockwise(third);
  return [toOffsets(spawn), toOffsets(second), toOffsets(third), toOffsets(fourth)];
}

function rotateClockwise(rows: readonly string[]): string[] {
  const n = rows.length;
  return Array.from({ length: n }, (_, row) =>
    Array.from({ length: n }, (_, col) => rows[n - 1 - col][row]).join(''),
  );
}

function toOffsets(rows: readonly string[]): Offset[] {
  const offsets: Offset[] = [];
  rows.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === 'X') offsets.push([x, y]);
    });
  });
  return offsets;
}
