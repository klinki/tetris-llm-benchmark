/** Guideline colors: each shape has its own color. */
export const COLORS: Record<PieceType, string> = {
  I: '#00f0f0',
  O: '#f0f000',
  T: '#a000f0',
  S: '#00f000',
  Z: '#f00000',
  J: '#0000f0',
  L: '#f0a000',
};

/** Bounding-box size per piece (I is 4x4, O is 2x2, the rest 3x3). */
export const BOX: Record<PieceType, number> = {
  I: 4, O: 2, T: 3, S: 3, Z: 3, J: 3, L: 3,
};

/** Spawn column: pieces spawn centered, rounded to the left. */
export const SPAWN_X: Record<PieceType, number> = {
  I: 3, O: 4, T: 3, S: 3, Z: 3, J: 3, L: 3,
};

/** Board storage id for a piece type (0 means empty). */
export function pieceId(type: PieceType): number {
  return PIECES.indexOf(type) + 1;
}

export function typeOfId(id: number): PieceType {
  return PIECES[id - 1];
}