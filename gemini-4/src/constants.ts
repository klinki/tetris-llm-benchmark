/**
 * Guideline gravity formula:
 * Time (in milliseconds) per row drop for a given level (1-indexed).
 * Formula: (0.8 - ((level - 1) * 0.007)) ^ (level - 1) seconds
 */
export function getGravityIntervalMs(level: number): number {
  const clampedLevel = Math.max(1, Math.min(level, 20));
  const seconds = Math.pow(0.8 - (clampedLevel - 1) * 0.007, clampedLevel - 1);
  return Math.max(16, seconds * 1000);
}
