// Tetromino definitions: SRS rotation states, wall kick tables and colors.
// Cells are [x, y] offsets inside the piece bounding box; y grows downward.

export type PieceType = 'I' | 'O' | 'T' | 'S' | 'Z' | 'J' | 'L';

export const PIECE_TYPES: PieceType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

// Guideline colors: each shape has a different color.
export const COLORS: Record<PieceType, string> = {
  I: '#00f0f0',
  O: '#f0f000',
  T: '#a000f0',
  S: '#00f000',
  Z: '#f00000',
  J: '#0000f0',
  L: '#f0a000',
};

export type Cells = [number, number][];

